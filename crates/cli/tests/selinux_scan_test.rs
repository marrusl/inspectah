//! SELinux custom modules and persistent booleans, end to end through the
//! scan path.
//!
//! The host is mocked files in the real policy store layout
//! (`/var/lib/selinux/<policy>/active`), run through the real SELinux
//! inspector by the scan command's own calls, then through both export
//! paths: the scan tarball's `render_all` and a refine session's export.
//! Nothing here builds a `SelinuxSection` by hand, so a collector that
//! reads the wrong store fails these tests instead of passing over a
//! fixture that shares its assumption.

use crate::sysctl_hosts::{
    SysctlHost, export_session, reload, render_export, scan_selinux, session,
};
use inspectah_core::aggregate::merge_snapshots;
use inspectah_core::snapshot::InspectionSnapshot;
use inspectah_core::types::selinux::SelinuxBoolean;

/// The active policy store on a package-mode RHEL 9 or 10 host.
const STORE: &str = "/var/lib/selinux/targeted/active";

/// `booleans.local` as libsemanage writes it after `setsebool -P
/// httpd_can_network_connect on` and `setsebool -P virt_use_nfs off`.
const BOOLEANS_LOCAL: &str = "# This file is auto-generated by libsemanage\n\
     # Do not edit directly.\n\
     \n\
     httpd_can_network_connect=1\n\
     virt_use_nfs=0\n";

/// An enforcing targeted host whose store holds a base module (100), a
/// packaged one (200), three local ones (400) and the module selinux-policy
/// generates at 400. The base module `apache` and the local `oldapp` are
/// turned off with `semodule -d`, which libsemanage records as an empty
/// file under `modules/disabled/`. Module directories hold the files
/// libsemanage writes. Two booleans are set persistently, and
/// `container_manage_cgroup` was switched on at runtime only, which sysfs
/// shows.
fn selinux_host() -> SysctlHost {
    let mut host = SysctlHost::new()
        .file("/sys/fs/selinux/enforce", "1\n")
        .file(
            "/etc/selinux/config",
            "SELINUX=enforcing\nSELINUXTYPE=targeted\n",
        );
    for (priority, module) in [
        ("100", "apache"),
        ("200", "container"),
        ("400", "myapp"),
        ("400", "permissive_rhcd_t"),
        ("400", "oldapp"),
        ("400", "extra_varrun"),
    ] {
        let dir = format!("{STORE}/modules/{priority}/{module}");
        host = host
            .file(&format!("{dir}/cil"), "")
            .file(&format!("{dir}/lang_ext"), "pp");
    }
    host.file(&format!("{STORE}/modules/disabled/apache"), "")
        .file(&format!("{STORE}/modules/disabled/oldapp"), "")
        .file(&format!("{STORE}/booleans.local"), BOOLEANS_LOCAL)
        .file("/sys/fs/selinux/booleans/container_manage_cgroup", "1 1\n")
}

/// The Security & Access Control block of an export's Containerfile.
fn selinux_block(tree: &std::path::Path) -> Vec<String> {
    let containerfile = std::fs::read_to_string(tree.join("Containerfile"))
        .expect("the export has a Containerfile");
    let lines: Vec<&str> = containerfile.lines().collect();
    let start = lines
        .iter()
        .position(|l| l.contains("Security & Access Control"))
        .unwrap_or_else(|| panic!("no SELinux block in:\n{containerfile}"));
    lines[start..]
        .iter()
        .skip(1)
        .take_while(|l| !l.starts_with("# ==="))
        .map(|l| (*l).to_string())
        .collect()
}

fn scanned() -> InspectionSnapshot {
    reload(&scan_selinux(selinux_host()))
}

/// The collector lists the local modules from the store, and only those.
#[test]
fn custom_modules_are_collected_from_the_policy_store() {
    let snap = scanned();
    let section = snap
        .selinux
        .as_ref()
        .expect("the SELinux section is present");
    assert_eq!(section.custom_modules, ["myapp", "permissive_rhcd_t"]);
}

/// Both export paths name every module the image does not carry, with
/// the commands that carry it, and render the same block.
#[test]
fn both_exports_name_the_modules_they_cannot_carry() {
    let snap = scanned();
    let scan_tree = render_export(&snap);
    let refine_tree = export_session(&session(&snap));

    let scan_block = selinux_block(scan_tree.path());
    assert!(
        scan_block.contains(
            &"# FIXME: 2 custom SELinux policy module(s) not carried: myapp, permissive_rhcd_t"
                .to_string()
        ),
        "{scan_block:#?}"
    );
    assert!(
        scan_block
            .iter()
            .any(|l| l == "# RUN semodule -i /tmp/selinux/*.cil && rm -rf /tmp/selinux/"),
        "{scan_block:#?}"
    );
    assert_eq!(selinux_block(refine_tree.path()), scan_block);
}

/// The collector reads the persistent booleans from `booleans.local`, off
/// as well as on, and not the runtime-only change.
#[test]
fn persistent_booleans_are_collected_from_the_policy_store() {
    let snap = scanned();
    let section = snap
        .selinux
        .as_ref()
        .expect("the SELinux section is present");
    assert_eq!(
        section.boolean_overrides,
        [
            SelinuxBoolean {
                name: "httpd_can_network_connect".into(),
                value: true,
            },
            SelinuxBoolean {
                name: "virt_use_nfs".into(),
                value: false,
            },
        ]
    );
}

/// Both export paths set each persistent boolean again with the command
/// that set it on the host, and nothing for the runtime-only one.
#[test]
fn both_exports_set_the_persistent_booleans() {
    let snap = scanned();
    let scan_block = selinux_block(render_export(&snap).path());
    let refine_block = selinux_block(export_session(&session(&snap)).path());

    let setsebool: Vec<&str> = scan_block
        .iter()
        .map(String::as_str)
        .filter(|l| l.contains("setsebool"))
        .collect();
    assert_eq!(
        setsebool,
        [
            "RUN setsebool -P httpd_can_network_connect on",
            "RUN setsebool -P virt_use_nfs off",
        ],
        "{scan_block:#?}"
    );
    assert_eq!(refine_block, scan_block);
}

/// The lines of a block that are commands, not comments.
fn commands(block: &[String]) -> Vec<&str> {
    block
        .iter()
        .map(String::as_str)
        .filter(|l| !l.trim_start().starts_with('#') && !l.trim().is_empty())
        .collect()
}

/// A module turned off with `semodule -d` is named in both exports, base
/// and local alike, and a disabled local module is not offered as an
/// active one: installing it as one would switch on policy the host
/// turned off.
#[test]
fn both_exports_name_the_disabled_modules_apart_from_the_active_ones() {
    let snap = scanned();
    let scan_block = selinux_block(render_export(&snap).path());
    let refine_block = selinux_block(export_session(&session(&snap)).path());

    for expected in [
        "# FIXME: 2 custom SELinux policy module(s) not carried: myapp, permissive_rhcd_t",
        "# FIXME: 2 SELinux policy module(s) disabled on the host with `semodule -d`, not carried: apache, oldapp",
        "# Custom, so install it first (`semodule -c -E <name>` on the host writes <name>.cil): oldapp",
        "# RUN semodule -d apache -d oldapp",
    ] {
        assert!(
            scan_block.iter().any(|l| l == expected),
            "missing {expected:?}: {scan_block:#?}"
        );
    }
    assert!(
        !commands(&scan_block).iter().any(|l| l.contains("semodule")),
        "a module command is executable: {scan_block:#?}"
    );
    assert_eq!(refine_block, scan_block);
}

/// A `modules/disabled/` that cannot be read is reported, not taken as
/// "nothing disabled": the scan says the modules listed as custom may
/// include disabled ones, and both exports still name those modules.
#[test]
fn an_unreadable_disabled_directory_is_reported() {
    let disabled = format!("{STORE}/modules/disabled");
    let snap = reload(&scan_selinux(
        selinux_host().dir_error(&disabled, std::io::ErrorKind::PermissionDenied),
    ));
    let warning = snap
        .warnings
        .iter()
        .find(|w| w.message.contains("modules/disabled/ in"))
        .unwrap_or_else(|| panic!("no warning names disabled/: {:?}", snap.warnings));
    assert!(
        warning.message.contains("may include disabled ones"),
        "{}",
        warning.message
    );
    let scan_block = selinux_block(render_export(&snap).path());
    assert!(
        scan_block.iter().any(|l| l
            == "# FIXME: 3 custom SELinux policy module(s) not carried: myapp, oldapp, permissive_rhcd_t"),
        "{scan_block:#?}"
    );
    assert_eq!(
        selinux_block(export_session(&session(&snap)).path()),
        scan_block
    );
}

/// A fleet host named `hostname` whose `booleans.local` holds `local`.
fn fleet_host(hostname: &str, local: &str) -> InspectionSnapshot {
    reload(&scan_selinux(
        SysctlHost::new()
            .file("/etc/hostname", &format!("{hostname}\n"))
            .file(
                "/etc/selinux/config",
                "SELINUX=enforcing\nSELINUXTYPE=targeted\n",
            )
            .file(&format!("{STORE}/modules/400/myapp/cil"), "")
            .file(&format!("{STORE}/booleans.local"), local),
    ))
}

/// Two hosts that set one boolean to different values: neither export of
/// the aggregate runs a `setsebool` for it, which would let host order
/// choose the image's value. A FIXME names the hosts and their values.
/// The boolean both hosts agree on is set once.
#[test]
fn a_fleet_boolean_set_differently_is_not_carried() {
    let hosts = vec![
        fleet_host("host-a", "httpd_can_network_connect=1\nvirt_use_nfs=1\n"),
        fleet_host("host-b", "httpd_can_network_connect=0\nvirt_use_nfs=1\n"),
    ];
    let (merged, _warnings) = merge_snapshots(hosts, None, None).expect("the two hosts merge");
    let merged = reload(&merged);

    let scan_block = selinux_block(render_export(&merged).path());
    let refine_block = selinux_block(export_session(&session(&merged)).path());
    let setsebool: Vec<&str> = commands(&scan_block)
        .into_iter()
        .filter(|l| l.contains("setsebool"))
        .collect();
    assert_eq!(
        setsebool,
        ["RUN setsebool -P virt_use_nfs on"],
        "{scan_block:#?}"
    );
    assert!(
        scan_block.iter().any(|l| l
            == "# FIXME: boolean httpd_can_network_connect is set differently across hosts, \
                not carried: on on host-a; off on host-b"),
        "{scan_block:#?}"
    );
    assert_eq!(refine_block, scan_block);
}

/// The files under `dir`, recursively.
fn files_under(dir: &std::path::Path) -> Vec<std::path::PathBuf> {
    let mut files = Vec::new();
    let mut pending = vec![dir.to_path_buf()];
    while let Some(dir) = pending.pop() {
        for entry in std::fs::read_dir(&dir).expect("an export directory reads") {
            let path = entry.expect("an export entry reads").path();
            if path.is_dir() {
                pending.push(path);
            } else {
                files.push(path);
            }
        }
    }
    files
}

/// `needle` is in no file either export of `snap` writes and nowhere in
/// refine's view or sections.
fn assert_in_no_export(snap: &InspectionSnapshot, needle: &str) {
    let scan_tree = render_export(snap);
    let session = session(snap);
    let refine_tree = export_session(&session);
    for (route, tree) in [("scan", &scan_tree), ("refine", &refine_tree)] {
        let files = files_under(tree.path());
        assert!(
            files
                .iter()
                .any(|f| f.ends_with("inspection-snapshot.json")),
            "{route}: {files:?}"
        );
        for file in files {
            let bytes = std::fs::read(&file).expect("an export file reads");
            assert!(
                !String::from_utf8_lossy(&bytes).contains(needle),
                "{route}: {} holds {needle:?}",
                file.display()
            );
        }
    }
    let view = serde_json::to_string(&inspectah_web::adapter::build_web_view(&session))
        .expect("the view serializes");
    assert!(!view.contains(needle), "refine's view holds {needle:?}");
    let sections = inspectah_web::adapter::build_web_sections(
        &inspectah_refine::projection::project_reference(&session.snapshot_projected()),
    );
    let sections = serde_json::to_string(&sections).expect("the sections serialize");
    assert!(
        !sections.contains(needle),
        "refine's sections hold {needle:?}"
    );
}

/// A `booleans.local` line the parser cannot read is reported by its line
/// number, and its text is in no file either export writes and nowhere in
/// refine's view or sections: a warning is not redacted, and the line can
/// hold anything.
#[test]
fn an_unreadable_booleans_local_line_reaches_no_export() {
    const SENTINEL: &str = "inspectah-sentinel-credential-9f3a";
    let local = format!("{BOOLEANS_LOCAL}api_token={SENTINEL}\n");
    let snap = reload(&scan_selinux(
        selinux_host().file(&format!("{STORE}/booleans.local"), &local),
    ));
    assert!(
        snap.warnings.iter().any(|w| w.message.contains("line 6")),
        "{:?}",
        snap.warnings
    );
    assert_in_no_export(&snap, SENTINEL);
}

/// A `store-root` that `semanage.conf` sets selects the store the
/// collector reads, and nothing of its text reaches a diagnostic: the
/// value runs to the end of its line, a `#` included, so an operator's
/// note after the path is part of it, and warnings are not redacted.
/// Each store problem the collector reports is hit: a store that is not
/// there (the modules and `booleans.local`), and one that is there but
/// whose priority directory, `disabled/` and a `booleans.local` line do
/// not read.
#[test]
fn a_configured_store_root_reaches_no_export() {
    const SENTINEL: &str = "inspectah-sentinel-credential-4b8e";
    let root = format!("/var/lib/selinux # password={SENTINEL}");
    let conf = format!("store-root = {root}\n");
    let store = format!("{root}/targeted/active");

    let missing = selinux_host().file("/etc/selinux/semanage.conf", &conf);
    let unreadable = selinux_host()
        .file("/etc/selinux/semanage.conf", &conf)
        .file(&format!("{store}/modules/400/myapp/cil"), "")
        .file(&format!("{store}/modules/disabled/apache"), "")
        .file(&format!("{store}/booleans.local"), "virt_use_nfs=maybe\n")
        .dir_iteration_error(
            &format!("{store}/modules/400"),
            std::io::ErrorKind::PermissionDenied,
        )
        .dir_error(
            &format!("{store}/modules/disabled"),
            std::io::ErrorKind::PermissionDenied,
        );
    // (host, the warnings it must raise, by a fragment of each)
    let cases: [(&str, SysctlHost, &[&str]); 2] = [
        (
            "missing store",
            missing,
            &["custom policy modules not read", "setsebool -P not read"],
        ),
        (
            "unreadable store",
            unreadable,
            &[
                "custom policy modules not read",
                "disabled policy modules not read",
                "booleans.local lines not read",
            ],
        ),
    ];
    for (case, host, expected) in cases {
        let snap = reload(&scan_selinux(host));
        for fragment in expected {
            assert!(
                snap.warnings.iter().any(|w| w.message.contains(fragment)),
                "{case}: no {fragment:?} warning: {:?}",
                snap.warnings
            );
        }
        assert_in_no_export(&snap, SENTINEL);
    }
}

/// A module name libsemanage does not accept is named in a FIXME, quoted
/// so it reads as one value, and is in no command suggestion: the store's
/// entries are directory names and can hold shell syntax, which an
/// operator uncommenting `# RUN semodule -d ...` or running
/// `semodule -c -E <name>` on the host would run. The valid names keep
/// their suggestions.
#[test]
fn a_module_name_libsemanage_refuses_gets_no_command_suggestion() {
    let mut host = selinux_host();
    for (priority, module) in [("400", "x;id"), ("400", "y$(id)")] {
        host = host.file(&format!("{STORE}/modules/{priority}/{module}/cil"), "");
    }
    for module in ["apache;id", "y$(id)", "nl\nRUN id"] {
        host = host.file(&format!("{STORE}/modules/disabled/{module}"), "");
    }
    let snap = reload(&scan_selinux(host));
    let scan_block = selinux_block(render_export(&snap).path());
    let refine_block = selinux_block(export_session(&session(&snap)).path());

    for expected in [
        "# FIXME: 2 custom SELinux policy module(s) not carried: myapp, permissive_rhcd_t",
        "# FIXME: 1 custom SELinux policy module(s) whose name libsemanage does not accept, \
         not carried, no command suggested: \"x;id\"",
        "# RUN semodule -i /tmp/selinux/*.cil && rm -rf /tmp/selinux/",
        "# FIXME: 2 SELinux policy module(s) disabled on the host with `semodule -d`, \
         not carried: apache, oldapp",
        "# FIXME: 3 SELinux policy module(s) disabled on the host whose name libsemanage \
         does not accept, no command suggested: \"apache;id\", \"nl\\nRUN id\", \"y$(id)\"",
        "# Custom, so install it first (`semodule -c -E <name>` on the host writes \
         <name>.cil): oldapp",
        "# RUN semodule -d apache -d oldapp",
    ] {
        assert!(
            scan_block.iter().any(|l| l == expected),
            "missing {expected:?}: {scan_block:#?}"
        );
    }
    for line in &scan_block {
        if line.contains("semodule") {
            for name in ["x;id", "y$(id)", "apache;id", "RUN id"] {
                assert!(!line.contains(name), "{name:?} is in {line:?}");
            }
        }
    }
    assert_eq!(
        commands(&scan_block),
        [
            "RUN setsebool -P httpd_can_network_connect on",
            "RUN setsebool -P virt_use_nfs off",
        ],
        "a module name escaped its comment: {scan_block:#?}"
    );
    assert_eq!(refine_block, scan_block);
}
